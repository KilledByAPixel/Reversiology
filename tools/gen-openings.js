// Builds src/openings.js from Egaroucid's list of named openings (GPL-3.0,
// https://github.com/Nyanyan/Egaroucid, bin/resources/openings/english/
// openings.txt; names from the Othello opening list by Robert Gatliff et al.).
// Each entry there is a board (0 black, 1 white); this finds the move
// sequence reaching it, starting with f5.
//   node tools/gen-openings.js <openings.txt> > src/openings.js
import { readFileSync } from 'node:fs';
import { Board, BLACK, WHITE, sqName } from '../src/board.js';

const lines = readFileSync(process.argv[2], 'utf8').split('\n').filter(l => l.trim())
  .sort((a, b) => a.slice(0, 64).replace(/\./g, '').length - b.slice(0, 64).replace(/\./g, '').length);
const out = [];
// Prefer move orders that continue an opening already named, so each line
// reads as the book plays it rather than as a transposition.
const known = () => out.map(o => o.moves);
for (const line of lines) {
  const board = line.slice(0, 64), name = line.slice(65).trim();
  const target = [...board].map(ch => ch === '0' ? BLACK : ch === '1' ? WHITE : 0);
  const n = target.filter(Boolean).length - 4;
  let found = null;
  const dfs = (b, moves) => {
    if (found) return;
    if (moves.length === n) {
      if (b.color.every((c, i) => c === target[i])) found = moves.slice();
      return;
    }
    let ms = b.legalMoves();
    if (!ms.length) { const t = b.clone(); t.play(-1); if (t.legalMoves().length) { dfs(t, moves); } return; }
    const prefix = moves.map(sqName).join('');
    const score = m => known().some(k => k.startsWith(prefix + sqName(m))) ? 0 : 1;
    ms = ms.sort((a, b) => score(a) - score(b));
    for (const m of ms) {
      if (!target[m]) continue;
      if (!moves.length && sqName(m) !== 'f5') continue;
      const t = b.clone(); t.play(m);
      moves.push(m); dfs(t, moves); moves.pop();
    }
  };
  dfs(new Board(), []);
  if (!found) { console.error('no sequence for', name); continue; }
  const moves = found.map(sqName).join('');
  if (!out.some(o => o.moves === moves && o.name === name)) out.push({ name, moves });
}
out.sort((a, b) => a.moves.length - b.moves.length || a.moves.localeCompare(b.moves));
console.log(`// Named openings, as move sequences starting with f5 (other first moves are
// the same openings mirrored). Generated by tools/gen-openings.js from
// Egaroucid's opening list (GPL-3.0), whose English names come from the
// Othello opening list by Robert Gatliff and others.
export const OPENINGS = [
${out.map(o => `  ['${o.moves}', ${JSON.stringify(o.name)}],`).join('\n')}
];`);
